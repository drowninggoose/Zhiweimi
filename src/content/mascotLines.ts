/** 展开成扁平列表，id 用「场景-调性-序号」保证稳定。 */
export const MASCOT_LINES: MascotLine[] = GROUPS.flatMap((group) =>
  group.list.map((text, index) => ({
    id: `${group.tag}-${group.tone}-${index + 1}`,
    tag: group.tag,
    tone: group.tone,
    text,
  })),
);

/** 各场景的句子。 */
export function linesForTag(tag: MascotTag): MascotLine[] {
  return MASCOT_LINES.filter((line) => line.tag === tag);
}

